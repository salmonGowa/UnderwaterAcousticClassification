"""Single entry point: build manifests and feature caches, run every experiment, write results.

    python -m src.run --config configs/<name>.yaml

Outputs go to results/<config name>/: one metrics JSON per experiment, figures,
and summary.md, which holds every number quoted in the README.
"""

import argparse
import json
import platform
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
import torch

from src.config import data_path, load_config
from src.data import deepship, shipsear, synthetic
from src.data import manifest as manifest_io
from src.evaluation import plots
from src.experiments import TaskData, cross_dataset, within_dataset
from src.features.cache import build_cache
from src.features.logmel import FeatureParams


def prepare_dataset(config, name, spec, rebuild):
    manifest_path = data_path(config, "manifests", f"{name}.csv")
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    if rebuild or not manifest_path.exists():
        if spec["source"] == "deepship":
            manifest = deepship.build_manifest(config["data_root"])
        elif spec["source"] == "shipsear":
            manifest = shipsear.build_manifest(config["data_root"])
        elif spec["source"] == "synthetic":
            manifest = synthetic.write_dataset(config["data_root"], name, **spec["params"])
        else:
            raise ValueError(f"unknown dataset source {spec['source']}")
        manifest_io.save(manifest, manifest_path)
        print(f"[data] {name}: wrote manifest with {len(manifest)} recordings", flush=True)
    manifest = manifest_io.load(manifest_path)
    build_cache(manifest, config["data_root"], FeatureParams.from_config(config["features"]))
    return manifest


def environment():
    return {"python": platform.python_version(), "numpy": np.__version__, "pandas": pd.__version__,
            "scikit-learn": sklearn.__version__, "torch": torch.__version__,
            "cuda": torch.cuda.is_available()}


def figures(config, experiment, result, predictions, out_dir):
    classes = result["classes"]
    reports = result.get("test") or result.get("cross")
    for name, report in reports.items():
        for level in ["segment", "recording"]:
            plots.confusion_figure(report[level], classes, f"{experiment['name']}: {name}, {level} level (test)",
                                   out_dir / f"confusion_{name}_{level}.png")
    if result.get("noise"):
        for level in ["segment", "recording"]:
            plots.noise_figure(result["noise"], level, f"{experiment['name']}: macro-F1 vs added ambient noise",
                               out_dir / f"noise_{level}.png")
    # Failure analysis on the best non-trivial model by test segment macro-F1.
    candidates = [m for m in reports if m != "majority"]
    if not candidates:
        return
    best = max(candidates, key=lambda m: reports[m]["segment"]["macro_f1"])
    pair = plots.most_confused_pair(reports[best]["segment"], classes)
    if pair:
        dataset = experiment.get("dataset") or experiment["target"]
        label_map = experiment.get("label_map") or experiment["target_label_map"]
        data = TaskData(config, dataset, label_map, classes, need_logmels=True)
        plots.failure_examples_figure(predictions[best], data.logmels, data.params, classes, pair,
                                      out_dir / f"failure_examples_{best}.png")
        result["failure_analysis"] = {"model": best, "true": pair[0], "predicted": pair[1], "segments": pair[2]}


def fmt(value, ci=None):
    return f"{value:.3f}" if ci is None else f"{value:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]"


def summary_markdown(config, results):
    lines = [f"# Results: {config['name']}", "",
             "Generated by `python -m src.run --config " + config["config_path"] + "`. Do not edit by hand.", ""]
    for r in results:
        lines += [f"## {r['experiment']}", ""]
        if "test" in r:
            lines += [f"Dataset: {r['dataset']}. Classes: {', '.join(r['classes'])}. Split unit: {r['split_unit']}.",
                      f"Test recordings per class: {r['counts']['test']['recordings']}; "
                      f"vessel groups per class: {r['counts']['test']['groups']}.", "",
                      "Grouped CV on the development set (mean ± std over folds; ± std over seeds):", "",
                      "| model | segment macro-F1 | recording macro-F1 |", "|---|---|---|"]
            for name, cv in r["cv"].items():
                s, rec = cv["segment_macro_f1"], cv["recording_macro_f1"]
                lines.append(f"| {name} | {s['mean']:.3f} ± {s['std_over_folds']:.3f} (seeds ± {s['std_over_seeds']:.3f}) "
                             f"| {rec['mean']:.3f} ± {rec['std_over_folds']:.3f} (seeds ± {rec['std_over_seeds']:.3f}) |")
            reports, chance = r["test"], r["chance_test"]
            lines += ["", "Hold-out test set (evaluated once; first seed; 95% bootstrap CI over recordings):", ""]
        else:
            lines += [f"Train on {r['source']}, test on {r['target']}. Classes: {', '.join(r['classes'])}.",
                      f"Target recordings per class: {r['counts']['target']['recordings']}; "
                      f"vessel groups per class: {r['counts']['target']['groups']}.", "",
                      "| model | in-domain CV segment macro-F1 | cross-dataset segment macro-F1 | drop |", "|---|---|---|---|"]
            for name in r["cross"]:
                lines.append(f"| {name} | {r['in_domain_cv'][name]['segment_macro_f1']['mean']:.3f} "
                             f"| {r['cross'][name]['segment']['macro_f1']:.3f} | {r['drop'][name]['segment']:.3f} |")
            reports, chance = r["cross"], r["chance_target"]
            lines += ["", f"Cross-dataset test on {r['target']} (first seed; 95% bootstrap CI over recordings):", ""]
        lines += ["| model | segment macro-F1 | segment balanced acc. | recording macro-F1 | recording balanced acc. |",
                  "|---|---|---|---|---|"]
        for name, rep in reports.items():
            seg, rec = rep["segment"], rep["recording"]
            lines.append(f"| {name} | {fmt(seg['macro_f1'], seg['ci95']['macro_f1'])} "
                         f"| {fmt(seg['balanced_accuracy'], seg['ci95']['balanced_accuracy'])} "
                         f"| {fmt(rec['macro_f1'], rec['ci95']['macro_f1'])} "
                         f"| {fmt(rec['balanced_accuracy'], rec['ci95']['balanced_accuracy'])} |")
        lines.append(f"| chance (uniform guess) | {fmt(chance['segment']['macro_f1'])} | {fmt(chance['segment']['balanced_accuracy'])} "
                     f"| {fmt(chance['recording']['macro_f1'])} | {fmt(chance['recording']['balanced_accuracy'])} |")
        for level, verdict in (r.get("clearly_beats") or {}).items():
            if verdict:
                lines.append(f"\nCNN vs best baseline ({verdict['best_baseline']}), {level} CV macro-F1: gain "
                             f"{verdict['gain']:+.3f}, threshold {verdict['threshold_run_to_run_std']:.3f} "
                             f"-> clearly beats: **{verdict['clearly_beats']}**")
        if r.get("noise"):
            lines += ["", "Macro-F1 (segment level, mean over seeds) vs added ambient noise:", "",
                      "| model | " + " | ".join(str(s) for s in r["noise"]["snr_db"]) + " |",
                      "|---|" + "---|" * len(r["noise"]["snr_db"])]
            for name, points in r["noise"]["models"].items():
                lines.append(f"| {name} | " + " | ".join(f"{p['segment']['macro_f1_mean']:.3f}" for p in points) + " |")
        if r.get("failure_analysis"):
            fa = r["failure_analysis"]
            lines.append(f"\nMost confused (test, {fa['model']}): true {fa['true']} predicted as {fa['predicted']} "
                         f"({fa['segments']} segments).")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", required=True)
    parser.add_argument("--rebuild-manifests", action="store_true")
    parser.add_argument("--only", nargs="*", help="run only these experiment names")
    args = parser.parse_args()
    config = load_config(args.config)

    for name, spec in config["datasets"].items():
        prepare_dataset(config, name, spec, args.rebuild_manifests)

    out_root = Path("results") / config["name"]
    out_root.mkdir(parents=True, exist_ok=True)
    results = []
    for experiment in config["experiments"]:
        if args.only and experiment["name"] not in args.only:
            continue
        out_dir = out_root / experiment["name"]
        out_dir.mkdir(exist_ok=True)
        runner = within_dataset if experiment["type"] == "within" else cross_dataset
        result, predictions = runner(config, experiment)
        figures(config, experiment, result, predictions, out_dir)
        result["environment"] = environment()
        result["config"] = {k: config[k] for k in ["features", "evaluation", "seeds", "split_seed", "cnn"]}
        with open(out_dir / "metrics.json", "w") as f:
            json.dump(result, f, indent=1)
        results.append(result)
        print(f"[done] {experiment['name']} -> {out_dir}", flush=True)

    (out_root / "summary.md").write_text(summary_markdown(config, results))
    print(f"[done] summary -> {out_root / 'summary.md'}")


if __name__ == "__main__":
    main()
